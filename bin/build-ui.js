#!/usr/bin/env node
// Optional developer build. The checked-in bundle runs without Node or npm.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const files = ['vendor/grid.js', 'vendor/qrcodegen.js', 'connection-qr.js', 'app.js'];
const source = files.map(file => fs.readFileSync(path.join(root, 'public/assets', file), 'utf8')
  .replace(/^import[^\n]+\n/gm, '')
  .replace(/^export \{[^\n]+\n/gm, '')
  .replace(/^export /gm, '')
  .replace(/[ \t]+$/gm, '')).join('\n');
const bundle = "// Generated by node bin/build-ui.js. Edit source modules, then rebuild.\n(() => { 'use strict';\n" + source + '\n})();\n';
new vm.Script(bundle, { filename: 'app.bundle.js' });
const target = path.join(root, 'public/assets/app.bundle.js');
fs.writeFileSync(target + '.tmp', bundle);
fs.renameSync(target + '.tmp', target);
console.log('UI bundle built and syntax checked.');
