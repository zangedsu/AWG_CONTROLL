#!/usr/bin/env node
// Optional developer build. The checked-in bundle runs without Node or npm.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const vendor = fs.readFileSync(path.join(root, 'public/assets/vendor/grid.js'), 'utf8').replace(/^export /gm, '');
const source = fs.readFileSync(path.join(root, 'public/assets/app.js'), 'utf8').replace(/^import[^\n]+\n/, '');
const bundle = "// Generated by node bin/build-ui.js. Edit app.js, then rebuild.\n(() => { 'use strict';\n" + vendor + '\n' + source + '\n})();\n';
new vm.Script(bundle, { filename: 'app.bundle.js' });
const target = path.join(root, 'public/assets/app.bundle.js');
fs.writeFileSync(target + '.tmp', bundle);
fs.renameSync(target + '.tmp', target);
console.log('UI bundle built and syntax checked.');
